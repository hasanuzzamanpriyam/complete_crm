$sections = [];
// Section banners span two lines in app.css:
//
//   /* =========================================================================
//   Component: bootstrap-reset.less
//   ========================================================================== */
//
// so the heading is the line AFTER the opening banner, not on the same line.
for ($i = 0; $i < $nLines; $i++) {
    if (!preg_match('~^\s*/\*\s*=+\s*$~', $lines[$i])) { continue; }
    $head = '';
    for ($j = $i + 1; $j < min($i + 4, $nLines); $j++) {
        $cand = trim($lines[$j]);
        if ($cand === '' || preg_match('~^=+\s*(\*/)?\s*$~', $cand)) { continue; }
        $head = $cand;
        break;
    }
    if ($head !== '') { $sections[] = ['line' => $i + 1, 'head' => $head]; }
}
// Close each section at the start of the next (or EOF).
$headingN = 0;
foreach ($sections as $i => $s) {
    $headingN++;
    $end = $i + 1 < count($sections) ? $sections[$i + 1]['line'] - 1 : $nLines;
    $add(sprintf('| %d | %d – %d | %s |', $headingN, $s['line'], $end, str_replace('|', '\|', $s['head'])));
}
$add();
$add(sprintf('_**%d sections mapped** — these become the A2-1 … A2-12 task boundaries._', count($sections)));
$add();

// -------------------------------------------------- 2. hex colours in app ----

// Delimiter is `~` because the pattern contains literal `#` characters; using `#`
// as the delimiter self-terminates the regex.
function tallyHex(string $text): array {
    preg_match_all('~(?:#[0-9a-fA-F]{8}|#[0-9a-fA-F]{6}|#[0-9a-fA-F]{3})\b~', $text, $m);
    $c = [];
    foreach ($m[0] as $v) { $k = strtolower($v); $c[$k] = ($c[$k] ?? 0) + 1; }
    arsort($c);
    return $c;
}

