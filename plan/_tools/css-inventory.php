function cfgValue(string $mysql, string $db, string $key): string {
    if (!$mysql) { return 'mysql not found'; }
    $sql = "SELECT LEFT(IFNULL(value,''),44) FROM tbl_config WHERE config_key='" . $key . "'";
    $cmd = sprintf('"%s" --user=root --database="%s" --batch --skip-column-names --execute="%s" 2>nul',
        $mysql, $db, str_replace('"', '\"', $sql));
    $r = trim((string) shell_exec($cmd));
    return $r === '' ? '(no row)' : $r;
}

